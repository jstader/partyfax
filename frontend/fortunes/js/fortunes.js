/* Lucky numbers as on the real slips: six different ones from 1 to 49,
   smallest first. `random` is Math.random's shape, for the tests. */
export function luckyNumbers(random = Math.random) {
  const picked = new Set();
  while (picked.size < 6) picked.add(1 + Math.floor(random() * 49));
  return [...picked].sort((a, b) => a - b);
}

/* A whole slip's contents, picked at random. */
export function pick(random = Math.random) {
  const one = (list) => list[Math.floor(random() * list.length)];
  return { fortune: one(FORTUNES), lesson: one(LESSONS), numbers: luckyNumbers(random) };
}
